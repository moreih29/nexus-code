function signal(): Float32Array {
  return Float32Array.from(
    { length: 8000 },
    (_, n) =>
      0.3 * Math.sin((2 * Math.PI * 440 * n) / 16000) +
      0.2 * Math.sin((2 * Math.PI * 1234.5 * n) / 16000 + 0.3) +
      0.05 * Math.sin((2 * Math.PI * 3100 * n) / 16000) * ((n % 7) / 7),
  );
}

describe("fbank", () => {
  test("counts Kaldi's frames: 25 ms every 10 ms, none past the end", () => {
    expect(frameCount(399)).toBe(0);
    expect(frameCount(400)).toBe(1);
    expect(frameCount(8000)).toBe(48);
  });

  test("matches Kaldi's log mel energies", () => {
    const features = fbank(signal());
    expect(features.length).toBe(REFERENCE.frames * MEL_BINS);
    for (const [frame, row] of Object.entries(REFERENCE.rows)) {
      const got = features.subarray(Number(frame) * MEL_BINS, (Number(frame) + 1) * MEL_BINS);
      for (let b = 0; b < MEL_BINS; b++)
        expect(Math.abs((got[b] as number) - (row[b] as number))).toBeLessThan(2e-3);
    }
  });

  test("takes each band's mean over time away", () => {
    const features = meanNormalized(fbank(signal()));
    const got = features.subarray(10 * MEL_BINS, 11 * MEL_BINS);
    for (let b = 0; b < MEL_BINS; b++)
      expect(Math.abs((got[b] as number) - (REFERENCE.cmn10[b] as number))).toBeLessThan(2e-3);
  });
});
